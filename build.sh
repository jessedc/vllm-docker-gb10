#!/usr/bin/env bash
# Repeatable from-source vLLM build for the DGX Spark (GB10 / sm_121a).
#
# Resolves and records the exact base-image digest and vLLM commit, then builds
# the image tagged with the short vLLM commit (plus :latest). Re-running with the
# same build.lock reproduces the same image.
#
# Usage:
#   ./build.sh                       # build the pinned vLLM release (see VLLM_REF)
#   ./build.sh --vllm-ref v0.27.1    # build a specific tag/branch/commit
#   ./build.sh --vllm-ref main       # bleeding edge (uses the nightly base image)
#   ./build.sh --base-image REF      # override the auto-derived base image
#   ./build.sh --refresh-base        # re-pull the base image, re-pin its digest
#   ./build.sh --no-cache            # force a clean rebuild
#   ./build.sh --reproduce           # rebuild exactly what build.lock records
set -euo pipefail
cd "$(dirname "$0")"

VLLM_REPO="https://github.com/vllm-project/vllm.git"
IMAGE_NAME="vllm-spark"
ARCH_LIST="12.1a"

# Latest tagged vLLM release. Releases are pinned explicitly rather than tracking
# main, so the base image below can be the *matching* official image.
VLLM_REF="v0.27.1"
BASE_REPO=""          # empty -> derived from VLLM_REF by base_for_ref()
REFRESH_BASE=0
NO_CACHE=""
REPRODUCE=0

# The base image must be the official vLLM image built from the same source ref:
# it then already ships the exact torch / flashinfer / CUDA stack that ref pins,
# and the only thing missing is sm_121a kernels -- which is what we recompile.
# (Every official image is built for 8.0-12.0 only; the Spark's GB10 is 12.1a.)
base_for_ref() {
  case "$1" in
    v[0-9]*) echo "vllm/vllm-openai:$1-aarch64" ;;   # tagged release
    *)       echo "vllm/vllm-openai:nightly-aarch64" ;;  # main / branch / SHA
  esac
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --vllm-ref)      VLLM_REF="$2"; shift 2 ;;
    --base-image)    BASE_REPO="$2"; shift 2 ;;
    --refresh-base)  REFRESH_BASE=1; shift ;;
    --no-cache)      NO_CACHE="--no-cache"; shift ;;
    --reproduce)     REPRODUCE=1; shift ;;
    -h|--help)       sed -n '2,15p' "$0"; exit 0 ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
done

[[ -n "$BASE_REPO" ]] || BASE_REPO="$(base_for_ref "$VLLM_REF")"

export DOCKER_BUILDKIT=1

# --- 1. resolve the base image digest (pin) --------------------------------
if [[ "$REPRODUCE" == 1 && -f build.lock ]]; then
  # shellcheck disable=SC1091
  source build.lock
  echo ">> reproducing build.lock: base=$BASE_DIGEST vllm=$VLLM_COMMIT"
else
  if [[ "$REFRESH_BASE" == 1 ]] || ! docker image inspect "$BASE_REPO" >/dev/null 2>&1; then
    echo ">> pulling base image $BASE_REPO ..."
    docker pull "$BASE_REPO"
  fi
  BASE_DIGEST="$(docker inspect --format '{{index .RepoDigests 0}}' "$BASE_REPO")"

  # --- 2. resolve the vLLM commit to build -------------------------------
  if [[ "$VLLM_REF" =~ ^[0-9a-f]{40}$ ]]; then
    VLLM_COMMIT="$VLLM_REF"
  else
    echo ">> resolving vLLM ref '$VLLM_REF' ..."
    VLLM_COMMIT="$(git ls-remote "$VLLM_REPO" "$VLLM_REF" "refs/tags/$VLLM_REF" "refs/heads/$VLLM_REF" \
                    | head -n1 | cut -f1)"
    [[ -z "$VLLM_COMMIT" ]] && { echo "could not resolve '$VLLM_REF'" >&2; exit 1; }
  fi
fi

SHORT="${VLLM_COMMIT:0:8}"
TAG="${IMAGE_NAME}:${SHORT}"

# A release build also gets a human-readable tag (vllm-spark:v0.27.1).
TAG_ARGS=(-t "$TAG" -t "${IMAGE_NAME}:latest")
REL_TAG=""
if [[ "$VLLM_REF" =~ ^v[0-9] ]]; then
  REL_TAG="${IMAGE_NAME}:${VLLM_REF}"
  TAG_ARGS+=(-t "$REL_TAG")
fi

echo "============================================================"
echo "  base image : $BASE_REPO"
echo "             : $BASE_DIGEST"
echo "  vllm ref   : $VLLM_REF -> $VLLM_COMMIT"
echo "  gpu arch   : $ARCH_LIST (sm_121a / GB10)"
echo "  image tags : $TAG , ${IMAGE_NAME}:latest${REL_TAG:+ , $REL_TAG}"
echo "============================================================"

# --- 3. build --------------------------------------------------------------
docker build $NO_CACHE \
  --build-arg "BASE_IMAGE=${BASE_DIGEST}" \
  --build-arg "VLLM_REPO=${VLLM_REPO}" \
  --build-arg "VLLM_REF=${VLLM_COMMIT}" \
  --build-arg "TORCH_CUDA_ARCH_LIST=${ARCH_LIST}" \
  "${TAG_ARGS[@]}" \
  .

# --- 4. record provenance --------------------------------------------------
cat > build.lock <<EOF
# Generated by build.sh -- pins for a reproducible rebuild (./build.sh --reproduce)
BASE_REPO="$BASE_REPO"
BASE_DIGEST="$BASE_DIGEST"
VLLM_REF="$VLLM_REF"
VLLM_COMMIT="$VLLM_COMMIT"
ARCH_LIST="$ARCH_LIST"
EOF

# --- 5. refresh vendored Grafana dashboards to match the built commit ------
# vLLM's own dashboards live in its source tree; keep our vendored copies in
# sync with $VLLM_COMMIT so panel queries match the metrics this image emits.
# Best-effort: a network hiccup must not fail an otherwise-good build.
DASH_DIR="observability/grafana/dashboards"
if [[ -d "$DASH_DIR" ]]; then
  raw="https://raw.githubusercontent.com/vllm-project/vllm/${VLLM_COMMIT}/examples/observability/dashboards/grafana"
  for d in performance_statistics.json query_statistics.json; do
    tmp="$(mktemp)"
    if curl -fsSL "$raw/$d" -o "$tmp" && head -c1 "$tmp" | grep -q '{'; then
      mv "$tmp" "$DASH_DIR/$d"
      echo ">> refreshed dashboard $d @ ${SHORT}"
    else
      rm -f "$tmp"
      echo ">> WARN: could not refresh $d (kept existing copy)" >&2
    fi
  done
fi

echo ">> done. Built $TAG"
echo ">> serve with:  ./run.sh <model-id>"
